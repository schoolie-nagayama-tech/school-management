-- ============================================================
-- 教室ごとのAI設定: キー名を実態に合わせる
-- ============================================================
-- 正典: docs/bulletin-ai-assist.html
--
-- ★この栓が止めているのは「掲示板の文章を外部（Anthropic）へ送ること」であって、
--   読み取りという1機能ではない。投稿を整える機能も同じ本文を送るので、同じ栓で止める。
--   キー名が bulletin_extract のままだと、読み取りだけの設定に見えて
--   「整えるは別なのでオンにしてよい」と誤解される。
--
-- ★スイッチは1つのまま。送るデータも、リーガルの判断も同じものなので、
--   機能ごとに分けると教室長が2つ見ることになり、片方だけオンの状態が生まれる。
-- ============================================================

UPDATE public.school_ai_settings
   SET feature_key = 'bulletin_ai', updated_at = now()
 WHERE feature_key = 'bulletin_extract';

COMMENT ON COLUMN public.school_ai_settings.feature_key IS
  '機能キー。bulletin_ai=掲示板の文章をAIに送ってよいか（読み取り・整える の両方）';
