-- ============================================================
-- 高校マスタに「地区」を足す
-- ============================================================
-- 神奈川の合格基準表（新教育研究協会）は地区の列で分かれている。
-- その列名を持つ場所が無かったので足す。
--
-- ★都立の old_district（旧学区・1〜10の数値）とは別物。
--   神奈川に学区制は無く（県立は全県一学区）、これは資料の並べ方でしかない。
--   「横浜東部・北部・川崎地区」のような文字列なので old_district（smallint）には入らない。
--
-- ★都立の行は NULL のまま。
-- ============================================================

ALTER TABLE public.high_schools
  ADD COLUMN IF NOT EXISTS region text;

COMMENT ON COLUMN public.high_schools.region IS
  '資料上の地区（神奈川の合格基準表の列）。都立は NULL。学区ではない（神奈川に学区制は無い）';
