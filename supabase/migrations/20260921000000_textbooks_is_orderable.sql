-- 発注の対象にしないテキストを表す列。
--
-- ★背景: 大学受験はレベル別・学校別にテキストが膨大にあり、実物を1冊ずつ教材マスタへ
--   登録するのは見合わない。そこで「大学受験日本史①」「共テ過去問 英語」のような
--   実在しない器のテキストに第1回〜第30回の単元だけを持たせ、実際に何をやるかは
--   進行表の引継ぎで指示する運用にした。志望校過去問（高校受験・中学受験・大学受験）も同じ器。
--
-- ★これらは実物が無い（赤本などは生徒が自分で買う）ので、発注リストに積まれると困る。
--   発注候補の条件は「テキスト名がある・未所持・未発注」だけで、教材(materials)の紐付けが
--   無くても発注時に自動で作られるため、名前があるだけで候補に上がってしまう。
--   is_active では止められない（進行表や提案書のピッカーからも丸ごと消えるため）。
--
-- ★本番へは Supabase MCP の apply_migration で適用済み（migration 名 textbooks_is_orderable）。
--   このファイルはローカル開発用。再適用しても壊れないよう if not exists にしてある。
alter table textbooks
  add column if not exists is_orderable boolean not null default true;

comment on column textbooks.is_orderable is
  '発注の対象にするか。false は実在しない器のテキスト（志望校過去問・大学受験の回数だけの器）で、進行表や提案書では選べるが発注リストには積まない。';
