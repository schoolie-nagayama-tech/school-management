/**
 * フリガナの正規化。
 *
 * ★ なぜ必要か: 生徒の検索・並び替えは last_name_kana / first_name_kana を使うため、
 *   ひらがなで登録されるとカタカナ検索から漏れる。ラベルを「フリガナ」に統一しても
 *   入力自体は防げない（IME の変換候補にひらがなが出る）ので、入り口で揃える。
 *   本番実測（2026-07-31）で 363 名中 7 名がひらがな混入していた。
 *
 * ★ 全角カタカナに寄せる: 既存データも検索も全角カタカナ前提のため、
 *   半角カナ（ｱ）はここでは変換しない。ひらがな→カタカナだけを扱う。
 */

/** ひらがな（ぁ〜ゖ）をカタカナに変換する。カタカナ・英数字・記号はそのまま。 */
export function toKatakana(value: string): string {
  // U+3041(ぁ)〜U+3096(ゖ) は同じ並びの U+30A1〜U+30F6 に 0x60 足すと対応する。
  // 「ゝ ゞ」(U+309D-309E) も同じ差分でカタカナ側に対応する。
  return value.replace(/[ぁ-ゖゝゞ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) + 0x60));
}
