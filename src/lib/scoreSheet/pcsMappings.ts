/**
 * PCS の単元 → 教材の単元（item_number）の対応表。
 * 正典: docs/score-sheet-plan-draft.md §6.2
 *
 * ★生徒ごとではなく教材ごと。PCS の単元名は様式で決まっていて変わらないので、第1段はコードに持つ
 *   （第2段で教材を広げるときにテーブル score_unit_mappings へ移す）。
 * ★空の配列は「この教材には当てはまる単元が無い」を明示している（書き忘れと区別する）。
 *   画面では「教材に当てはまる単元が無いもの」として一覧に出る。
 * ★鍵は pcsKey(群名, 単元名)。同じ単元名が別の群にあるため（「文字式の利用」が中1と中2の両方）。
 * ★単元は item_number で指す。フォレスタステップ1年は「1-1」が2回出てくる（後ろは小学校の復習）ので、
 *   最初に出てくる単元を使う（resolveItemNumbers 側の約束）。
 *
 * 対応づけは 2026-09-29 に Opus が作り、教室長が「ほぼ正しい。あとは人が手直しする程度」と確認した。
 */

import { pcsKey } from './pcsParse';
import type { ScoreSubject } from './types';

export interface PcsTextbookMapping {
  /** 本番の textbooks を名前・科目・学年で引く（ID はローカルと本番で違いうるため持たない） */
  textbook: { name: string; subject: string; grade: string };
  subject: ScoreSubject;
  /** 数学の「計算の範囲」。章番号（item_number の「-」の前）と、個別の単元 */
  calcRange?: { chapters: string[]; extra: string[] };
  /** pcsKey → item_number[] */
  map: Record<string, string[]>;
}

/** 読みやすさのために [群, 単元, 単元番号[]] で書いて、鍵に直す */
function build(rows: [string, string, string[]][]): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const [g, u, nos] of rows) out[pcsKey(g, u)] = nos;
  return out;
}

const range = (prefix: string, from: number, to: number) =>
  Array.from({ length: to - from + 1 }, (_, i) => `${prefix}-${from + i}`);

