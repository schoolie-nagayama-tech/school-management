/** 生徒の学年（中1=7, 中2=8）と教科から、初めに選んでおく教材の対応表 */
export function defaultPcsMapping(
  subject: ScoreSubject,
  studentGrade: number | null
): PcsTextbookMapping | null {
  const grade = studentGrade === 7 ? '1年' : '2年';
  return (
    PCS_TEXTBOOK_MAPPINGS.find((m) => m.subject === subject && m.textbook.grade === grade) ?? null
  );
}
