/**
 * 入力欄の下に出す質問の例。
 *
 * ★理由: ヘルプへは歯車メニューから入るので、開いた時点で「何の話か」の手がかりがない。
 *   空の入力欄だけを出すと何を打てばいいか分からず、結局キーワード検索に戻ってしまう。
 *   ★FAQの見出しをそのまま並べない。見出しを写すだけならキーワード検索と同じで、
 *   「普通の言葉で聞いていい」ことが伝わらない。実際に困ったときの言い方で書く。
 *
 * 押すとその文が入って、そのまま質問が飛ぶ。
 */

import type { RoleTag } from '@/lib/help/faqData';

/**
 * 誰にでも出す（役割で分かれない困りごと）。
 *
 * ★ここに置く例は、講師から見える項目（roles に teacher を含むか未指定）に
 *   当たるものだけにする。上位ロール専用の項目は講師には渡らないので、
 *   講師が押すと必ず「載っていません」になる。
 */
const COMMON: string[] = ['報告書を書き終わったのに提出できない', '授業の記録はどこに書くの'];

/**
 * 役割ごとに、その人がよく詰まるところ。
 *
 * ★例は「日々の業務でつまずく場面」から選ぶ。機能名を並べても、困っている人は
 *   その機能名にたどり着けなくて困っているので手がかりにならない。
 * ★答えられない例を置かない。押した1回目が外れると「使えない」と判断されて
 *   二度と使われない。実際、以前ここにあった「教室を追加したい」は本番ログで
 *   unanswered になっていた（該当するFAQ項目が無い）ので外した。
 * ★未公開・試作の機能（座席表・保護者ポータルv2・講習Web申込）も置かない。
 *   答えとしては正しくても「まだ使えません」で終わり、最初の一歩にならない。
 */
const BY_ROLE: Record<RoleTag, string[]> = {
  teacher: ['出勤簿はどこから出すの', '前回の引継ぎを見ながら報告書を書きたい'],
  // 教室長の定例業務から。承認・締め・催促といった「止まると誰かが待つ」ものを前に置く
  manager: [
    '講師が出した報告書はどこで承認するの',
    '9月請求分って何月分のこと',
    '出勤簿の承認待ちが溜まっている',
    '要面談の生徒を見つけたい',
    'アラートが消えないんだけど',
    '保護者から来た申込が生徒に紐づかない',
  ],
  admin: ['講師のアカウントを作りたい', 'ユーザーのロールを変えたい', '代理ログインしたい'],
  /**
   * ロールが取れていないとき用。★この状態では filterIndexByRole がロール指定のある
   * 項目を全部落とすため、見えるのは「誰でも読める19項目」だけになる。
   * 業務の例を並べても必ず外れるので、ロールに依存しない困りごとだけを置く。
   * COMMON まで到達しないよう4件そろえておく（4件で打ち切られる）。
   */
  all: ['ログインできない', 'パスワードを変えたい', '勝手にログアウトされる', '設定はどこにあるの'],
};

/**
 * その画面・その役割に合わせた例を最大4件返す。
 * ページ内のヘルプ（ContextHelp）から呼ぶときは pageTopics にそのページの話題を渡す。
 */
export function exampleQuestions(role: RoleTag, pageTopics?: string[]): string[] {
  // 画面の中から聞くときは、その画面の話題を優先する（そのページの話だと分かるように）
  const head = (pageTopics ?? []).filter((t) => t.trim() !== '').slice(0, 2);
  const rest = [...(BY_ROLE[role] ?? BY_ROLE.all), ...COMMON];

  const out: string[] = [];
  for (const q of [...head, ...rest]) {
    if (!out.includes(q)) out.push(q);
    if (out.length >= 4) break;
  }
  return out;
}
