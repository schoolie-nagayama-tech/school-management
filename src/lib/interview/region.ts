/**
 * 教室がどの都県の入試を相手にしているか。
 * ------------------------------------------------------------------
 * ★③「時期の重要性」と「入試まであと◯日」は、都県が違えば中身がまるごと変わる。
 *   都立は1020点の総合得点1本・併願優遇は12月15日の入試相談、神奈川は打診値表と
 *   前期/後期の内申 ―― 混ぜて話すと面談でそのまま事故る。
 *
 * ★DBの列にしていない。理由は2つ。
 *   1. 教室は4つしかなく、増えるのは年に0〜1校。
 *   2. ここで選ぶ先（scenes.ts の定型トーク）はコードの中にある。自由記述の列にすると
 *      「神奈川」と打った教室が黙って定型トークを失う。取りうる値をコードで閉じておく。
 *   FC展開で教室が増えたら、ここに1行足してから使う。
 */

export type Region = 'tokyo' | 'kanagawa';

export const REGION_LABEL: Record<Region, string> = {
  tokyo: '東京都',
  kanagawa: '神奈川県',
};

/** 教室ID（schools.id）→ 都県 */
const REGION_BY_SCHOOL_ID: Record<string, Region> = {
  '9f519794-3673-4e90-b1ea-88a79f70174a': 'tokyo', // 京王堀之内校
  'd187f7a3-633a-46ce-8d32-c56c85d17bac': 'tokyo', // 永山校
  // ★清瀬校は埼玉県境だが東京のまま。都内在住の生徒は埼玉の公立の全日制に出願できない
  //   （隣接県協定に東京都は入っていない）ので、面談の相手は都立と私立。埼玉の日程・定型トークは
  //   足さない（2026-09-23決定）。埼玉の入試制度はAIヘルプ（faqData.ts「高校入試の制度」）にだけ置く。
  'e26b398c-8e30-47bc-b528-ee92fd45be7f': 'tokyo', // 清瀬校
  '9a6b5996-a266-47ed-878f-85e93c2b8b90': 'kanagawa', // 緑園都市校
  // デモ校（保護者ポータル体験）。実在の生徒はいないが、面談画面を見せるときに
  // 定型行が空だと何も伝わらないので東京都として扱う
  'd0000000-0000-4000-8000-000000000001': 'tokyo',
};

/**
 * 教室から都県を出す。未登録の教室は null。
 *
 * ★未登録を「東京都」に寄せない。神奈川の教室が1校ある以上、既定値を東京にすると
 *   登録し忘れた教室で都立の話が出てしまう。出ないほうが安全（定型行が消えるだけで、
 *   教室長はすぐ気づく）。
 */
export function regionOfSchool(schoolId: string | null | undefined): Region | null {
  if (!schoolId) return null;
  return REGION_BY_SCHOOL_ID[schoolId] ?? null;
}
